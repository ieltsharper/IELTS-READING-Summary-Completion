// One-shot guides for the Summary Completion page.
//   node _generator/oneshot-apply.mjs --check    validate only
//   node _generator/oneshot-apply.mjs            validate, then write oneshot.js (loaded by index.html)
// Guide file: _generator/strategy/<exId>.json
// { "step1": "...", "types": [["Câu","Dạng","Locate trước được?","Từ khóa để scan"], ...], "typesNote": "...",
//   "walk": [ { "para": "Đoạn A", "idea": "...", "answers": [ { "q": 32, "ans": "shells", "quote": "text from passage", "how": "..." } ], "note": "..." } ],
//   "tips": ["..."] }
import fs from 'node:fs';
import path from 'node:path';
import { root, loadExercises, stripHtml, norm } from './lib.mjs';

const checkOnly = process.argv.includes('--check');
const E = loadExercises();
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
let problems = 0;
const bad = (id, msg) => { problems++; console.log(`  PROBLEM ${id}: ${msg}`); };

function render(g) {
  const h = [];
  h.push('<h3>Bước 1 – Đọc tiêu đề, nắm chủ đề</h3><p>' + esc(g.step1) + '</p>');
  h.push('<h3>Bước 2 – Phân loại câu hỏi</h3><table>' + g.types.map((r, i) => '<tr>' + r.map((c) => (i ? '<td>' : '<th>') + esc(c) + (i ? '</td>' : '</th>')).join('') + '</tr>').join('') + '</table>');
  if (g.typesNote) h.push('<p>' + esc(g.typesNote) + '</p>');
  h.push('<h3>Bước 3 – Đọc One-Shot: đến đoạn nào chốt hết câu hỏi của đoạn đó</h3>');
  for (const w of g.walk) {
    h.push('<p><b>' + esc(w.para) + ' – </b>' + esc(w.idea) + '</p>');
    const items = [];
    for (const a of w.answers || []) items.push('<li><b>Câu ' + esc(a.q) + ' → ' + esc(a.ans) + '.</b> ' + esc(a.how) + (a.quote ? ' <i>Trích: “' + esc(a.quote) + '”</i>' : '') + '</li>');
    if (w.note) items.push('<li><b>Lưu ý:</b> ' + esc(w.note) + '</li>');
    if (items.length) h.push('<ul>' + items.join('') + '</ul>');
  }
  if (g.tips?.length) h.push('<h3>Bẫy cần tránh</h3><ul>' + g.tips.map((t) => '<li>' + esc(t) + '</li>').join('') + '</ul>');
  return h.join('');
}

const out = {};
let done = 0;
for (const e of E) {
  const f = path.join(root, '_generator', 'strategy', `${e.id}.json`);
  if (!fs.existsSync(f)) continue;
  let g;
  try { g = JSON.parse(fs.readFileSync(f, 'utf8')); } catch (x) { bad(e.id, 'invalid JSON: ' + x.message); continue; }
  if (!g.step1 || !Array.isArray(g.types) || !g.types.length || !Array.isArray(g.walk) || !g.walk.length) { bad(e.id, 'missing step1/types/walk'); continue; }
  const body = norm(stripHtml(e.passage.replace(/<\/p>/g, ' ')));
  const seen = new Set();
  for (const w of g.walk) {
    if (!w.para || !w.idea) bad(e.id, 'walk item without para/idea');
    for (const a of w.answers || []) {
      const q = e.questions.find((x) => x.num === Number(a.q));
      if (!q) { bad(e.id, `Q${a.q} is not in this exercise`); continue; }
      seen.add(q.num);
      const ok = q.answers.map(norm);
      if (!ok.includes(norm(a.ans))) bad(e.id, `Q${a.q} answer "${a.ans}" differs from key "${q.answers.join(' / ')}"`);
      if (!a.how) bad(e.id, `Q${a.q} has no explanation`);
      if (a.quote) for (const frag of String(a.quote).split(/\.{3}|…/).map(norm).filter((x) => x.length > 2)) if (!body.includes(frag)) bad(e.id, `Q${a.q} quote not in passage: "${frag}"`);
    }
  }
  for (const q of e.questions) if (!seen.has(q.num)) bad(e.id, `Q${q.num} not covered`);
  out[e.id] = render(g);
  done++;
}
console.log(`${done} guide file(s) read, ${problems} problem(s)`);
if (!checkOnly && !problems) {
  fs.writeFileSync(path.join(root, 'oneshot.js'), '// Generated by _generator/oneshot-apply.mjs from _generator/strategy/*.json\nconst ONESHOT = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log('wrote oneshot.js');
}
process.exit(problems ? 1 : 0);
